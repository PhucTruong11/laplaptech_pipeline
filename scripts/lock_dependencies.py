"""Freeze only the runtime dependency closure, never the whole developer venv.

Evaluate both Windows/Linux Python 3.13 markers; fail if installed versions do not
satisfy a requirement. This records a resolved environment, it is not a resolver.
"""
from importlib import metadata
from pathlib import Path
from packaging.markers import default_environment
from packaging.requirements import Requirement
from packaging.utils import canonicalize_name


def main():
    root = Path(__file__).resolve().parents[1]
    pending = [Requirement(line.strip()) for line in (root / 'requirements.in').read_text().splitlines()
               if line.strip() and not line.startswith('#')]
    pinned, visited = {}, set()
    while pending:
        req = pending.pop()
        name = canonicalize_name(req.name)
        version = metadata.version(name)
        if req.specifier and not req.specifier.contains(version, prereleases=True):
            raise RuntimeError(f'Installed {name}=={version} does not satisfy {req}')
        pinned[name] = version
        key = (name, tuple(sorted(req.extras)))
        if key in visited:
            continue
        visited.add(key)
        for value in metadata.requires(name) or []:
            child = Requirement(value)
            include = child.marker is None
            for platform, system, os_name in [('linux', 'Linux', 'posix'), ('win32', 'Windows', 'nt')]:
                for extra in {'', *req.extras}:
                    env = {**default_environment(), 'sys_platform': platform, 'platform_system': system,
                           'os_name': os_name, 'python_version': '3.13', 'python_full_version': '3.13.15', 'extra': extra}
                    include = include or (child.marker is not None and child.marker.evaluate(env))
            if include:
                pending.append(child)
    header = '# Generated by scripts/lock_dependencies.py; Python 3.13 runtime closure.\n'
    (root / 'requirements.lock.txt').write_text(header + ''.join(f'{n}=={v}\n' for n, v in sorted(pinned.items())), encoding='utf-8')
    print(f'Locked {len(pinned)} runtime dependencies')


if __name__ == '__main__':
    main()
